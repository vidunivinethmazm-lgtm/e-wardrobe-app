PHI_BACK = 1.5 * math.pi

def proc2mh(u_proc, v_proc):
    """Convert procedural UV (v=0=bottom, v=1=top) to MakeHuman UV (v=0=top, v=1=bottom)."""
    phi = 2 * math.pi * u_proc + PHI_BACK
    theta = math.pi * (1 - v_proc)
    x = math.sin(theta) * math.cos(phi)
    y = math.cos(theta)
    z = math.sin(theta) * math.sin(phi)
    mag = math.sqrt(x*x + y*y + z*z)
    if mag > 0: x/=mag; y/=mag; z/=mag
    u_mh = 0.5 + math.atan2(x, z) / (2 * math.pi)
    v_mh = 0.5 - math.asin(max(-1.0, min(1.0, y))) / math.pi
    if u_mh < 0: u_mh += 1.0
    if u_mh >= 1.0: u_mh -= 1.0
    return (round(u_mh, 4), round(v_mh, 4))

