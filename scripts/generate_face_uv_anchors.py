def propagate_uvs(known_uvs, num_landmarks=478):
    """Propagate UV coordinates from known anchors to all landmarks using
    graph diffusion on the face mesh topology.

    Parameters
    ----------
    known_uvs : dict[int, tuple[float, float]]
        Known UV anchors {landmark_index: (u, v)}.
    num_landmarks : int
        Total number of landmarks (468 or 478).

    Returns
    -------
    dict[int, tuple[float, float]]
        UV coordinates for all landmarks.
    """
    # Build adjacency list
    adj = {i: [] for i in range(num_landmarks)}
    for a, b in FACEMESH_TESSELATION:
        if a < num_landmarks and b < num_landmarks:
            adj[a].append(b)
            adj[b].append(a)

    # Initialize: known anchors get their UVs, others get NaN
    uvs = {i: np.array([np.nan, np.nan], dtype=np.float32) for i in range(num_landmarks)}
    for idx, (u, v) in known_uvs.items():
        if idx < num_landmarks:
            uvs[idx] = np.array([u, v], dtype=np.float32)

    # Iterative diffusion: propagate UVs from known anchors to neighbors
    # Use multiple iterations to propagate through the graph
    for _ in range(50):
        changed = False
        new_uvs = {i: uvs[i].copy() for i in range(num_landmarks)}
        for i in range(num_landmarks):
            if np.any(np.isnan(uvs[i])):
                # Get neighbors with known UVs
                neighbor_uvs = []
                for nb in adj[i]:
                    if nb < len(uvs) and not np.any(np.isnan(uvs[nb])):
                        neighbor_uvs.append(uvs[nb])
                if neighbor_uvs:
                    new_uvs[i] = np.mean(neighbor_uvs, axis=0)
                    changed = True
        uvs = new_uvs
        if not changed:
            break

    # For any remaining NaN landmarks, fall back to nearest known by index
    known_indices = sorted(known_uvs.keys())
    for i in range(num_landmarks):
        if np.any(np.isnan(uvs[i])):
            nearest = min(known_indices, key=lambda k: abs(k - i))
            uvs[i] = uvs[nearest].copy()

    return {i: (float(uvs[i][0]), float(uvs[i][1])) for i in range(num_landmarks)}


